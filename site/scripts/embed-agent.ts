/**
 * Embeds the FiveM agent (../fivem/fiverax_agent) into the site, so the panel can hand it out as a .zip
 * (GET /api/agent/download): the site is deployed alone (Vercel), without the rest of the repository.
 *
 *   npm run embed-agent        (after every change of the agent; a test fails while the copy is stale)
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const agentDir = path.resolve(root, "../fivem/fiverax_agent");
const out = path.join(root, "src/lib/agent-files.generated.ts");

const files = fs.readdirSync(agentDir)
  .filter((name) => fs.statSync(path.join(agentDir, name)).isFile())
  .sort()
  .map((name) => ({ path: name, content: fs.readFileSync(path.join(agentDir, name), "utf8").replace(/\r\n/g, "\n") }));
const manifest = files.find((f) => f.path === "fxmanifest.lua")?.content ?? "";
const version = /^version\s+'([^']+)'/m.exec(manifest)?.[1] ?? "0.0.0";

fs.writeFileSync(
  out,
  `// Generated by scripts/embed-agent.ts from fivem/fiverax_agent: do not edit (npm run embed-agent).\n` +
    `export const AGENT_VERSION = ${JSON.stringify(version)};\n` +
    `export const AGENT_FILES: { path: string; content: string }[] = ${JSON.stringify(files, null, 1)};\n`
);
console.log(`fiverax_agent ${version}: ${files.length} files, ${Math.round(files.reduce((n, f) => n + f.content.length, 0) / 1024)} KB -> ${path.relative(root, out)}`);
